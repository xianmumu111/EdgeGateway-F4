#ifndef MB_MASTER_H
#define MB_MASTER_H

/* =====================================================================
 * mb_master.h —— Modbus RTU **主站**协议层
 *
 * EdgeGateway-F4 / Module M3
 * 作者: 周雄伟   版本: 0.1.0（骨架）   日期: 2026-09-16
 *
 * ---------------------------------------------------------------------
 * 一、为什么主站比从站难
 * ---------------------------------------------------------------------
 * 从站是被动的：来一帧、回一帧，收不到就不回，逻辑是"一条直线"。
 * 主站是主动的：发出去之后要**自己盯着**——
 *
 *     多久算超时？ 收到的是不是我等的那个从站回的？
 *     长度对不对？ CRC 对不对？ 是正常帧还是异常帧？
 *
 * 所以主站本质上是一个**带超时的状态机**，本文件只负责其中
 * "不涉及硬件"的那一半：组帧、预判响应长度、校验、解析。
 * 收发和超时留给 port 层（和从站的 mb_port_f1.c 对称）。
 *
 * ---------------------------------------------------------------------
 * 二、主站手里最大的便宜：响应长度是**可预判**的
 * ---------------------------------------------------------------------
 * 这是主站和从站最不一样的地方，也是分帧的关键。
 * 从站不知道请求会有多长（收到才知道），但主站**知道自己刚才发了什么**，
 * 所以能精确算出从站应该回几个字节：
 *
 *   功能码        正常响应长度              异常帧
 *   0x03 读保持   5 + 2*qty               5 字节
 *   0x06 写单个   8（把请求原样回显）      5 字节
 *
 * 异常帧永远是 5 字节：addr | fc|0x80 | 异常码 | CRC_L | CRC_H
 *
 * ⚠️ 但要小心：异常帧比正常响应**短**。如果主站傻等 5+2*qty 个字节，
 * 从站回了个异常帧，主站就会一直等到超时——白白浪费一个超时周期。
 *
 * 正确做法（本模块的 mb_master_rsp_len 就是干这个的）：
 *   收到【前 3 个字节】就够了：
 *     第 1 字节 = 从站地址
 *     第 2 字节 = 功能码   ← 最高位为 1 说明是异常帧，总共只要 5 字节
 *     第 3 字节 = 字节计数 / 异常码
 *   用这 3 个字节就能定下整帧长度，然后按这个数收剩下的。
 *
 * ---------------------------------------------------------------------
 * 三、主站必须校验什么（从站不用管这些）
 * ---------------------------------------------------------------------
 * 从站只需校验"收到的帧对不对"；主站还要额外校验
 * "**收到的响应和我刚才的请求对不对得上**"：
 *
 *   1) CRC            —— 整帧算一遍，含 CRC 域自身之外的所有字节
 *   2) 地址           —— 响应里的 addr 必须 == 请求里的 addr
 *                        （总线串扰时可能收到别的从站的迟到响应）
 *   3) 功能码         —— 正常时 == 请求的 fc；异常时 == 请求的 fc | 0x80
 *                        （收到一个完全不相关的 fc = 总线上有别的通信）
 *   4) 字节计数       —— 0x03 响应的第 3 字节必须 == 2 * qty
 *   5) 寄存器起始地址 —— 0x06 回显的地址必须 == 请求的地址
 *
 * 这五条里，第 2、3 条是从站不用做、主站必须做的。面试问
 * "主站和从站的校验有什么不同"，答这个。
 *
 * ---------------------------------------------------------------------
 * 四、大小端
 * ---------------------------------------------------------------------
 * Modbus 线上是**大端**（高字节在前），STM32 是小端。
 * 组帧要转成大端发出去，解析要把收到的转成小端。忘掉这一步，
 * 现象是"读出来的数是 0x0A00 而不是 0x000A"——值被整体换了高低字节。
 * ===================================================================== */

#include <stdint.h>

/* ---------------------------------------------------------------------
 * 五、返回码
 * --------------------------------------------------------------------- */
typedef enum {
    MB_M_OK        = 0,  /* 收到合法响应，数据已解析 */
    MB_M_CRC_ERR   = 1,  /* CRC 校验失败 */
    MB_M_ADDR_ERR  = 2,  /* 响应里的从站地址和请求对不上 */
    MB_M_FC_ERR    = 3,  /* 功能码既不是正常响应也不是对应的异常帧 */
    MB_M_LEN_ERR   = 4,  /* 帧长不合法（太短，或字节计数对不上） */
    MB_M_EXCEPTION = 5,  /* 从站回了异常帧（**这是合法响应**，不是错误） */
    MB_M_NO_SPACE  = 6,  /* 输出缓冲区放不下解析出的寄存器 */
    MB_M_TIMEOUT   = 7,  /* 超时没收到 —— 这个由 port 层产生，本层不产生 */
    MB_M_BAD_ARG   = 8   /* 调用方参数不合法（buf 太小 / 数量为 0 等） */
} mb_m_err_t;

/* 把返回码转成能打印的字符串，调试用 */
const char *mb_m_err_str(mb_m_err_t e);

/* ---------------------------------------------------------------------
 * 六、组帧
 * ---------------------------------------------------------------------
 * 把请求装进 buf，返回帧长度（字节数）；返回 0 表示参数不合法。
 *
 * ⚠️ buf 至少要 8 字节。0x03 和 0x06 的请求帧都是固定 8 字节：
 *      addr(1) + fc(1) + 数据(4) + CRC(2)
 */

/* 0x03 读保持寄存器：从 slave 的 start 号寄存器开始，读 qty 个
 *   qty 合法范围 1~125（Modbus 规定一次最多读 125 个保持寄存器） */
uint16_t mb_master_build_read(uint8_t *buf, uint16_t buf_max,
                              uint8_t slave, uint16_t start, uint16_t qty);

/* 0x06 写单个寄存器：把 slave 的 addr 号寄存器写成 val */
uint16_t mb_master_build_write_single(uint8_t *buf, uint16_t buf_max,
                                      uint8_t slave, uint16_t addr, uint16_t val);

/* ---------------------------------------------------------------------
 * 七、预判响应长度（主站分帧的核心）
 * ---------------------------------------------------------------------
 * 给出【已经收到的前几个字节】head，算出这一整帧应该有多长。
 *
 *   head_len >= 3  -> 能算出来，返回总长度（>=5）
 *   head_len <  3  -> 信息不够，返回 0，调用方继续收
 *
 * req 是刚才发出去的请求帧（要拿里面的 fc 和 qty）。
 * 异常处理：若 head[1] & 0x80，直接返回 5。
 */
uint16_t mb_master_rsp_len(const uint8_t *req, uint16_t req_len,
                           const uint8_t *head, uint16_t head_len);

/* ---------------------------------------------------------------------
 * 八、校验 + 解析
 * ---------------------------------------------------------------------
 * req/rsp 分别是我发出去的请求和收到的响应。
 *
 * 成功（MB_M_OK）：
 *     out[] 填解析出的寄存器值（已转成**本机字节序**），*out_n = 个数。
 *     0x03 -> out_n = qty；0x06 -> out_n = 1（回显的值）
 * 异常（MB_M_EXCEPTION）：
 *     *exc 填异常码（0x01 非法功能码 / 0x02 非法地址 / 0x03 非法值）
 *     ⚠️ 收到异常帧是**通信成功**，只是从站拒绝执行。别当成通信故障。
 * 其余：出错，out 内容无意义。
 */
mb_m_err_t mb_master_parse(const uint8_t *req, uint16_t req_len,
                           const uint8_t *rsp, uint16_t rsp_len,
                           uint16_t *out, uint16_t out_max, uint16_t *out_n,
                           uint8_t *exc);

#endif /* MB_MASTER_H */
